    parser = argparse.ArgumentParser(
        description="Execute documentation notebooks and collect warnings.",
        epilog=(
            "Examples:\n"
            "  python tools/docs/execute_notebooks/execute_notebooks.py                  # All docs/\n"
            "  python tools/docs/execute_notebooks/execute_notebooks.py user_guides      # Only docs/user_guides/\n"
            "  python tools/docs/execute_notebooks/execute_notebooks.py quick-start faq  # Multiple subdirs\n"
            "  python tools/docs/execute_notebooks/execute_notebooks.py user_guides/hyperparameter-tuning-and-lags-selection.ipynb\n"
            "  python tools/docs/execute_notebooks/execute_notebooks.py --include-slow   # Also run SLOW_NOTEBOOKS\n"
            "  python tools/docs/execute_notebooks/execute_notebooks.py --check          # Scan saved outputs, no execution\n"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "targets",
        nargs="*",
        default=None,
        help="Subdirectories or notebook files (relative to docs/) to execute. "
             "Examples: 'user_guides', 'user_guides/backtesting.ipynb'. "
             "If omitted, all notebooks under docs/ are executed.",
    )
    parser.add_argument(
        "--include-slow",
        action="store_true",
        help="Also execute the notebooks listed in SLOW_NOTEBOOKS, which are "
             "skipped by default when scanning directories. A slow notebook "
             "passed explicitly as a file target is always executed.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not execute anything: scan the saved outputs of every notebook "
             "in scope (excluded and slow ones included) for error outputs, "
             "unexecuted code cells and warnings. Exit code 1 if any notebook "
             "has errors or unexecuted cells.",
    )
    args = parser.parse_args()
    sys.exit(
        run_notebooks(
            targets=args.targets or None,
            include_slow=args.include_slow,
            check=args.check,
        )
    )
