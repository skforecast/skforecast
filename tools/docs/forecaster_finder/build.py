"""
Generate everything the forecaster finder publishes from its single source
(finder.py) and the results of its study (benchmarks/forecaster_finder/):

- docs/javascripts/finder-data.json: rows, results of every combination of
  answers and scripts, read by docs/javascripts/finder.js.
- The generated blocks of docs/quick-start/choose-a-forecaster.md (evidence,
  rules and an example script), which are the page without JavaScript.
- The rules block of skills/choosing-a-forecaster/SKILL.md.
- first_comparison.ipynb, the notebook that "Run it in Google Colab" opens.

Before writing, every distinct script (it includes its sample data) is run in
an empty namespace, as pasted into a new notebook, followed by the lines that
forecast with each model. The build fails if a script
raises an error or any warning, if a line is longer than 88 characters, if a
sentence shown with a result is no longer supported by the study or if a
linked user guide does not exist.

Usage:
    python tools/docs/forecaster_finder/build.py            # run the scripts and write
    python tools/docs/forecaster_finder/build.py --check    # nothing is run or written:
                                                            # fails if a file is out of date
    python tools/docs/forecaster_finder/build.py --no-run   # write without running
                                                            # (to iterate on texts)
    python tools/docs/forecaster_finder/build.py --ai       # also the lines of skforecast-ai
                                                            # (needs that package)
"""
import json
import re
import sys
import time
import traceback
import warnings
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
import finder  # noqa: E402

STUDY = ROOT / "benchmarks" / "forecaster_finder" / "results"
DATA = ROOT / "docs" / "javascripts" / "finder-data.json"
PAGE = ROOT / "docs" / "quick-start" / "choose-a-forecaster.md"
SKILL = ROOT / "skills" / "choosing-a-forecaster" / "SKILL.md"
NOTEBOOK = HERE / "first_comparison.ipynb"
SITE = "https://skforecast.org/latest/"
GENERATED = "generated by tools/docs/forecaster_finder/build.py, do not edit by hand"
# Answers of the script shown on the page without JavaScript
EXAMPLE = {"target": "number", "series": "one", "freq": "daily", "extra": "no"}
MAX_LINE = 88
# Warnings that depend on the data, not on the script: scikit-learn raises
# this one when a category that is predicted does not appear in a short test
# period (quarterly data: 8 values).
DATA_WARNINGS = {"UserWarning: y_pred contains classes not in y_true"}


def run(code, after=""):
    """
    Run a script in an empty namespace, as in a new notebook, followed by
    `after` (lines that continue the script: the forecast, or skforecast-ai).
    Returns (error, warnings).
    """
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        try:
            exec(compile(code + "\n" + after, "script", "exec"), {})
            error = None
        except Exception:
            error = traceback.format_exc(limit=2).strip().splitlines()[-1][:200]
    seen = sorted({f"{w.category.__name__}: {str(w.message).strip().splitlines()[0][:140]}"
                   for w in caught} - DATA_WARNINGS)
    return error, seen


def key(a):
    """Identifier of a set of answers, complete or not (also the hash of the page)."""
    return "-".join(a.get(k) or "_" for k in ("target", "series", "freq", "extra"))


def evidence():
    """
    Figures of the section "How we chose these rules" and the checks of the
    sentences shown with each result (finder.REASON), from the results of the
    study (benchmarks/forecaster_finder/rules.py). A sentence that the results
    stop supporting makes the build fail: the rule has to be rewritten.
    """
    cells = pd.read_csv(STUDY / "rules_cells.csv").set_index("cell")
    runs = pd.read_csv(STUDY / "rules_runs.csv")
    tuned = pd.read_csv(STUDY / "rules_tuned.csv")
    clf = pd.read_csv(STUDY / "extra_classification.csv").set_index("model")
    low = runs[(runs.n_series == 1) & runs.freq.isin(["monthly", "quarterly"])]
    low = low.groupby("dataset")[["fm", "ml", "arima"]].mean()
    names = {"one series, nothing known in advance": ("one-none", "One series, nothing known in advance"),
             "one series, known in advance": ("one-known", "One series, variables known in advance"),
             "several series": ("several", "Several series")}
    table, checks = [], {}
    for cell, (leaf, label) in names.items():
        c = cells.loc[cell]
        n, ahead = int(c["datasets"]), int(c["Chronos-2 ahead (datasets)"])
        worse = int(c["LightGBM >= naive (datasets)"])
        table.append({"data": label, "datasets": n, "chronos_ahead": ahead,
                      "lightgbm_ahead": n - ahead, "lightgbm_below_baseline": worse,
                      "chronos_below_baseline": int(c["Chronos-2 >= naive (datasets)"])})
        if leaf == "one-none":
            checks[leaf] = ahead >= 0.75 * n and worse >= 0.25 * n
        else:
            checks[leaf] = ahead > 0.5 * n and ahead < n
    checks["stats"] = (low.arima < low.ml).mean() > 0.5
    checks["category"] = (clf.loc["LightGBM classifier [refit]", "balanced_accuracy"]
                          <= clf.loc["Same hour yesterday", "balanced_accuracy"] + 0.02)
    stats = {"datasets": len(low), "arima_ahead_of_lightgbm": int((low.arima < low.ml).sum()),
             "arima_ahead_of_chronos": int((low.arima < low.fm).sum())}
    search = {"pairs": int(tuned["datasets"].sum()),
              "lightgbm_ahead": int(tuned["tuned < Chronos-2"].sum()),
              "improved": int(tuned["tuning improved LightGBM"].sum())}
    return {"datasets": int(runs.dataset.nunique()), "table": table, "stats": stats,
            "search": search, "checks": checks}


