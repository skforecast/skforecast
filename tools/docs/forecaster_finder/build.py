def evidence_markdown(facts):
    """Table and sentences of "How we chose these rules"."""
    rows = "\n".join(
        f"| {r['data']} | {r['datasets']} | {r['chronos_ahead']} of {r['datasets']} | "
        f"{r['lightgbm_ahead']} of {r['datasets']} | "
        f"{r['lightgbm_below_baseline']} of {r['datasets']} |"
        for r in facts["table"]
    )
    s, t = facts["stats"], facts["search"]
    return (
        f"Each model was run with the same backtesting on {facts['datasets']} public datasets, "
        "with every model using all the data before each test period. The error is the MASE "
        "(the mean absolute error, scaled so that datasets can be compared), and each dataset "
        "counts once in each row. Some datasets appear in more than one row, with and without "
        f"their known variables or with one and several series, so the rows add up to "
        f"{sum(r['datasets'] for r in facts['table'])} cases.\n\n"
        "| Your data | Datasets | Chronos-2 had the lower error | LightGBM had the lower error "
        "| LightGBM did worse than the baseline |\n"
        "|:--|--:|--:|--:|--:|\n"
        f"{rows}\n\n"
        f"- Chronos-2 did not do worse than the baseline in any dataset.\n"
        f"- With an automatic search of 20 trials, LightGBM improved in {t['improved']} of the "
        f"{t['pairs']} cases and had a lower error than Chronos-2 in {t['lightgbm_ahead']}.\n"
        f"- In the {s['datasets']} monthly and quarterly datasets with one series, ARIMA had a "
        f"lower error than LightGBM in {s['arima_ahead_of_lightgbm']} and than Chronos-2 in "
        f"{s['arima_ahead_of_chronos']}."
    )


def rules_rows(link):
    """Rows of the rules table. `link(cls)` writes a class name, linked or not."""
    c = link
    base = c("ForecasterEquivalentDate")
    return [
        ("A number, one series",
         f"{c('ForecasterRecursive')} with LightGBM and {c('ForecasterFoundation')} with Chronos-2",
         f"{base}: the value one season before"),
        ("A number, one monthly or quarterly series",
         f"The same two, and {c('ForecasterStats')} with ARIMA as a reference",
         f"{base}: the value one season before"),
        ("A number, several series",
         f"{c('ForecasterRecursiveMultiSeries')} with LightGBM and {c('ForecasterFoundation')} "
         "with Chronos-2",
         f"{base}, one per series"),
        ("A category",
         f"{c('ForecasterRecursiveClassifier')} with a LightGBM classifier",
         "The category one season before (`y.shift(season)`)"),
    ]


def rules_markdown(link):
    rows = "\n".join(f"| {a} | {b} | {c} |" for a, b, c in rules_rows(link))
    return (
        "| Your data | Forecasters to compare | Baseline |\n|:--|:--|:--|\n" + rows + "\n\n"
        "If you know variables in advance (holidays, promotions, prices), pass them as `exog` "
        "to the forecasters. ARIMA is run without them."
    )


def history_sentence():
    parts = [f"{f['history_text']} of {name} data" for name, f in finder.FREQ.items()
             if f.get("history_text")]
    return "The scripts need at least " + ", ".join(parts[:-1]) + " or " + parts[-1] + "."


def page_blocks(facts):
    """Generated blocks of the page, by marker name."""
    guide = lambda cls: f"[`{cls}`](../{finder.GUIDES[cls].replace('.html', '.ipynb')})"  # noqa: E731
    leaf = finder.decide(EXAMPLE)
    return {
        "EVIDENCE": evidence_markdown(facts),
        "RULES": rules_markdown(guide) + "\n\n" + history_sentence(),
        "EXAMPLE": "```python\n" + finder.render(EXAMPLE, leaf) + "```",
    }


def skill_block(facts):
    """Rules block of the skill `choosing-a-forecaster`, for AI assistants."""
    labels = {key: label for key, label, _ in finder.ROWS[2]["options"]}
    settings = "\n".join(
        f"| {labels[name]} | `{f['alias']}` | {f['season']} | {f['steps']} | `{f['lags']}` | "
        f"{f['min_history']} |"
        for name, f in finder.FREQ.items() if not f.get("edit")
    )
    rows = "\n".join(
        f"| {r['data']} | {r['chronos_ahead']} of {r['datasets']} | "
        f"{r['lightgbm_below_baseline']} of {r['datasets']} |" for r in facts["table"]
    )
    s, t = facts["stats"], facts["search"]
    return (
        "For a new problem, compare these forecasters on the same folds and keep what beats "
        "the baseline. They are two candidates with different roles, not a ranking.\n\n"
        "Pass the same `TimeSeriesFold(refit=True, fixed_train_size=False)` to every "
        "backtesting function, so that every model uses all the data before each fold: "
        "`backtesting_stats` refits every estimator except `Sarimax` in each fold and "
        "`backtesting_foundation` always forecasts from the history up to the fold, so with "
        "`refit=False` only the model you train would forecast from old data. "
        "`backtesting_foundation` warns that `refit` does not apply to it: pass "
        "`suppress_warnings=True` there.\n\n"
        + rules_markdown(lambda cls: f"`{cls}`") + "\n\n"
        "Chronos-2 is `FoundationModel(\"autogluon/chronos-2-small\")` (Apache-2.0, no "
        "training). LightGBM is the model the user trains and shapes with their own variables.\n\n"
        "Example settings per frequency so that a first script runs (they are not tuned):\n\n"
        "| One value per | `freq` | `season` (offset of the baseline) | `steps` | `lags` | "
        "Minimum history (values) |\n|:--|:--|--:|--:|:--|--:|\n" + settings + "\n\n"
        f"Evidence ({facts['datasets']} public datasets, MASE, every model using all the data "
        "before each test period, one vote per dataset, LightGBM not tuned):\n\n"
        "| Data | Chronos-2 had the lower error | LightGBM did worse than the baseline |\n"
        "|:--|--:|--:|\n" + rows + "\n\n"
        f"Chronos-2 did not do worse than the baseline in any dataset. With an automatic search "
        f"of 20 trials, LightGBM had a lower error than Chronos-2 in {t['lightgbm_ahead']} of "
        f"{t['pairs']} cases. In the {s['datasets']} monthly and quarterly datasets with one "
        f"series, ARIMA had a lower error than LightGBM in {s['arima_ahead_of_lightgbm']}. "
        "Domain features and knowledge of the problem are not measured: on a given dataset a "
        "trained model can still win."
    )


def replace_block(text, name, content, path):
    """Replace what is between the markers of the block `name` (None: unnamed)."""
    tag = "FORECASTER-FINDER" + (f":{name}" if name else "")
    pattern = re.compile(rf"(<!-- {tag}:START[^>]*-->\n).*?(<!-- {tag}:END -->)", re.S)
    if not pattern.search(text):
        raise SystemExit(f"{path.relative_to(ROOT)}: markers of the block {tag} not found")
    return pattern.sub(lambda m: m.group(1) + content + "\n" + m.group(2), text)


def notebook():
    """Colab notebook with an install cell and a cell to paste the script into."""
    def cell(kind, source):
        base = {"cell_type": kind, "metadata": {}, "source": source.splitlines(keepends=True)}
        return base if kind == "markdown" else {**base, "outputs": [], "execution_count": None}
    return {
        "nbformat": 4, "nbformat_minor": 5,
        "metadata": {"kernelspec": {"display_name": "Python 3", "name": "python3"}},
        "cells": [
            cell("markdown",
                 "# Your first comparison with skforecast\n\n"
                 "1. Run the first cell to install the libraries (about a minute).\n"
                 "2. Paste the script you copied from the skforecast documentation into the "
                 "second cell and run it.\n\n"
                 "The script includes sample data, so it runs as it is. To use your own "
                 "data, replace its data block.\n\n"
                 f"Get a script: {SITE}quick-start/choose-a-forecaster.html"),
            cell("code", '%pip install -q "skforecast[stats]" lightgbm chronos-forecasting'),
            cell("code", "# Paste your script here (Ctrl+V or Cmd+V) and run this cell\n"),
        ],
    }


def page_data(facts):
    """Data of the page (finder-data.json) and the distinct scripts with their answers."""
    scripts, combos = {}, {}
    for a in finder.all_answers():
        leaf = finder.decide(a)
        code = finder.render(a, leaf)
        sid = scripts.setdefault(code, {"id": f"s{len(scripts)}", "answers": a})["id"]
        combos[key(a)] = {
            "why": finder.reasons(leaf), "snippet": sid, "needs": finder.needs(a),
            "forecast": finder.forecast_snippet(a, leaf),
            # The prompt is completed on the page with the script
            "prompt": finder.prompt(a, leaf, code).split("```python")[0],
            "skforecast_ai": finder.ai_snippet(a), "agent": finder.agent_message(a),
        }
    data = {
        "rows": finder.ROWS, "notes": finder.NOTES,
        "intro": finder.INTRO.format(datasets=facts["datasets"]),
        "script_steps": finder.SCRIPT_STEPS, "colab": finder.COLAB,
        "next": finder.NEXT,
        "partial": {key(a): finder.blocks(a) for a in finder.all_partial_answers()},
        "combos": combos,
        "snippets": {info["id"]: code for code, info in scripts.items()},
    }
    return data, scripts


def outputs(facts):
    """Every generated file as {path: text}, and the distinct scripts."""
    data, scripts = page_data(facts)
    page = PAGE.read_text()
    for name, content in page_blocks(facts).items():
        page = replace_block(page, name, content, PAGE)
    files = {
        DATA: json.dumps(data, indent=1) + "\n",
        PAGE: page,
        SKILL: replace_block(SKILL.read_text(), None, skill_block(facts), SKILL),
        NOTEBOOK: json.dumps(notebook(), indent=1) + "\n",
    }
    return files, scripts


def static_checks(facts, scripts):
    """Checks that need no execution. Returns the list of problems."""
    problems = [f"sentence not supported by the study: {k}"
                for k, ok in facts["checks"].items() if not ok]
    docs = ROOT / "docs"
    for guide in [*finder.GUIDES.values(), finder.EXOG_GUIDE,
                  *(page for _, page in finder.NEXT.values())]:
        if not any((docs / guide).with_suffix(ext).exists() for ext in (".ipynb", ".md")):
            problems.append(f"user guide that does not exist: {guide}")
    for code, info in scripts.items():
        try:
            compile(code, "script", "exec")
        except SyntaxError as exc:
            problems.append(f"{info['id']}: {exc}")
        forecast = finder.forecast_snippet(info["answers"], finder.decide(info["answers"]))
        problems += [f"{info['id']}: line longer than {MAX_LINE} characters: {line}"
                     for line in (code + forecast).splitlines() if len(line) > MAX_LINE]
    return problems


def run_ai(scripts):
    """Run the lines of skforecast-ai after each script. Returns the ones that fail."""
    import importlib.metadata as md

    failed = []
    for code, info in scripts.items():
        after = finder.ai_snippet(info["answers"])
        if after is None:
            continue
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            error, _ = run(code, after=after)
        print("skforecast-ai", info["id"], error or "ok", json.dumps(info["answers"]), flush=True)
        if error:
            failed.append(f"{info['id']} with skforecast-ai: {error}")
    print({p: md.version(p) for p in ("skforecast-ai", "skforecast", "pandas")})
    return failed


def main(argv):
    facts = evidence()
    files, scripts = outputs(facts)
    problems = static_checks(facts, scripts)

    if "--check" in argv:
        stale = [str(path.relative_to(ROOT)) for path, text in files.items()
                 if not path.exists() or path.read_text() != text]
        for line in problems:
            print(line)
        if stale:
            print("Out of date (run `python tools/docs/forecaster_finder/build.py`): "
                  + ", ".join(stale))
        if not (problems or stale):
            print(f"Forecaster finder up to date: {len(scripts)} scripts, {len(files)} files.")
        return 1 if problems or stale else 0

    if "--no-run" not in argv:
        print(f"{len(scripts)} distinct scripts", flush=True)
        for code, info in scripts.items():
            start = time.perf_counter()
            a = info["answers"]
            error, seen = run(code, after=finder.forecast_snippet(a, finder.decide(a)))
            status = "ok" if error is None and not seen else (error or "; ".join(seen))
            print(info["id"], status, f"{time.perf_counter() - start:.1f} s",
                  json.dumps(info["answers"]), flush=True)
            if status != "ok":
                problems.append(f"{info['id']}: {status}")
    if "--ai" in argv:
        problems += run_ai(scripts)

    for line in problems:
        print(line)
    if problems:
        print("Nothing written.")
        return 1
    for path, text in files.items():
        path.write_text(text)
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
