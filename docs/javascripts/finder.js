/*
 * Forecaster finder (docs/quick-start/choose-a-forecaster.md).
 *
 * Progressive enhancement: renders the questions, the answer box and the script
 * inside #sk-finder from the JSON named in its data-src attribute. It does
 * nothing on pages without #sk-finder, and the page is complete without it
 * (rules table and example script). With navigation.instant, `document$` emits
 * on every page change: the previous instance is destroyed before a new one
 * starts.
 *
 * The page holds no rules: every state, complete or not, comes from the data,
 * generated by tools/docs/forecaster_finder/build.py. The answers are kept in
 * the hash of the URL (#answers=number-one-daily-no), so a result can be shared
 * and survives going to a user guide and back.
 */
(function () {
  "use strict";

  var current = null;
  var KEYS = ["target", "series", "freq", "extra"];
  var KEYWORDS = { "import": 1, "from": 1, "for": 1, "in": 1, "if": 1, "else": 1, "print": 1,
                   "True": 1, "False": 1, "None": 1, "lambda": 1 };

  function esc(s) {
    return String(s).replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }

  /* Minimal Python highlighting: comments, strings, keywords, classes and numbers. */
  function highlight(code) {
    return code.split("\n").map(function (line) {
      var out = "", i = 0, rest, m, w;
      while (i < line.length) {
        rest = line.slice(i);
        if (rest[0] === "#") { out += '<span class="tk-m">' + esc(rest) + "</span>"; break; }
        if ((m = rest.match(/^f?("[^"]*"|'[^']*')/))) {
          out += '<span class="tk-s">' + esc(m[0]) + "</span>"; i += m[0].length; continue;
        }
        if ((m = rest.match(/^[A-Za-z_][A-Za-z0-9_]*/))) {
          w = m[0];
          out += KEYWORDS[w] === 1 ? '<span class="tk-k">' + w + "</span>"
               : /^[A-Z][a-z]/.test(w) ? '<span class="tk-c">' + w + "</span>" : esc(w);
          i += w.length; continue;
        }
        if ((m = rest.match(/^\d+(\.\d+)?/))) {
          out += '<span class="tk-n">' + m[0] + "</span>"; i += m[0].length; continue;
        }
        out += esc(rest[0]); i += 1;
      }
      return out;
    }).join("\n");
  }

  /* Events go to Google Analytics only if the reader accepted it: Material
     defines gtag after the consent. Closed identifiers only, never free text. */
  function track(name, params) {
    if (typeof gtag === "function") gtag("event", name, params || {});
  }

  function mount(root, D) {
    var state = {};
    var previous = {};        // Text of each block in the last render, to flash what changed
    var showImports = false;
    var editing = null;       // Question reopened from its chip (narrow screens)
    var lastLines = null;     // Lines of the last complete script, to flash the ones that change
    var open = {};            // Folded sections that are open
    var narrow = window.matchMedia("(max-width: 59.99em)");

    root.innerHTML =
      '<p class="skf-head">' + esc(D.intro) + "</p>" +
      '<form class="skf-rows"></form>' +
      '<div class="skf-result" aria-live="polite"><div class="skf-answer"></div>' +
      '<div class="skf-script"></div></div>';
    root.removeAttribute("data-state");
    document.body.classList.add("sk-finder-ready");
    var elRows = root.querySelector(".skf-rows");
    var elAnswer = root.querySelector(".skf-answer");
    var elScript = root.querySelector(".skf-script");
    elRows.addEventListener("submit", function (e) { e.preventDefault(); });

    function visible(row) {
      return !row.show_if || Object.keys(row.show_if).every(function (k) {
        return state[k] === row.show_if[k];
      });
    }
    function rowsShown() { return D.rows.filter(visible); }
    function key() {
      return KEYS.map(function (k) {
        return (k === "series" && state.target !== "number") ? "_" : (state[k] || "_");
      }).join("-");
    }
    function clear() { Object.keys(state).forEach(function (k) { delete state[k]; }); }

    function fromHash() {
      var m = (location.hash || "").match(/^#answers=([a-z_]+(?:-[a-z_]+){3})$/);
      if (!m) return false;
      var parts = m[1].split("-"), next = {};
      for (var i = 0; i < KEYS.length; i++) {
        if (parts[i] === "_") continue;
        var row = D.rows[i];
        if (!row.options.some(function (o) { return o[0] === parts[i]; })) return false;
        next[KEYS[i]] = parts[i];
      }
      if (next.target !== "number") delete next.series;
      clear();
      Object.keys(next).forEach(function (k) { state[k] = next[k]; });
      return true;
    }

    /* ---------- questions ---------- */
    function rowHtml(r, n) {
      var chosen = state[r.id];
      return '<fieldset class="skf-row' + (chosen ? " done" : "") + '" data-row="' + r.id +
        '" role="radiogroup" aria-labelledby="skf-lg-' + r.id + '">' +
        '<legend id="skf-lg-' + r.id + '"><span class="skf-n">' + n + "</span>" + esc(r.text) +
        "</legend>" + (r.hint ? '<div class="skf-hint">' + esc(r.hint) + "</div>" : "") +
        '<div class="skf-opts">' + r.options.map(function (o, i) {
          var tab = chosen ? chosen === o[0] : i === 0;
          return '<button type="button" class="skf-opt" role="radio" data-row="' + r.id +
            '" data-value="' + o[0] + '" aria-checked="' + (chosen === o[0]) + '" tabindex="' +
            (tab ? 0 : -1) + '">' + esc(o[1]) + (o[2] ? "<small>" + esc(o[2]) + "</small>" : "") +
            "</button>";
        }).join("") + "</div></fieldset>";
    }

    function chipText(r, o) {
      if (r.id === "freq" && o[0] !== "other") return "One value per " + o[1].toLowerCase();
      if (r.id === "extra") return "Known in advance: " + o[1].toLowerCase();
      return o[1];
    }

    function renderRows() {
      var rows = rowsShown();
      var reset = Object.keys(state).length
        ? '<button type="button" class="skf-reset">Start over</button>' : "";
      if (!narrow.matches) {
        elRows.innerHTML = rows.map(function (r, n) { return rowHtml(r, n + 1); }).join("") + reset;
        return;
      }
      /* Narrow screens: one question open at a time, so the answer box stays in
         view right below it. The answered ones become chips that reopen them. */
      var pending = rows.filter(function (r) { return !state[r.id]; })[0];
      var openRow = (editing && rows.some(function (r) { return r.id === editing; }))
        ? editing : (pending ? pending.id : null);
      var chips = rows.filter(function (r) { return state[r.id] && r.id !== openRow; })
        .map(function (r) {
          var o = r.options.filter(function (x) { return x[0] === state[r.id]; })[0];
          return '<button type="button" class="skf-chip" data-edit="' + r.id +
            '" aria-label="Change: ' + esc(r.text) + '">' + esc(chipText(r, o)) + " ✎</button>";
        }).join("");
      var n = rows.map(function (r) { return r.id; }).indexOf(openRow);
      elRows.innerHTML = (chips ? '<div class="skf-chips">' + chips + "</div>" : "") +
        (openRow ? rowHtml(rows[n], n + 1) : "") + reset;
    }

    /* ---------- answer box ---------- */
    function blockHtml(b, changed) {
      var pending = b.forecasters.length > 1;
      var fc = b.forecasters.map(function (f, n) {
        return (n ? '<span class="skf-or">or</span>' : "") + '<span class="skf-fc">' +
          esc(f.cls).replace(/([a-z])([A-Z])/g, "$1<wbr>$2") +
          (f.when ? "<small>" + esc(f.when) + "</small>" : "") + "</span>";
      }).join("");
      var guides = b.forecasters.map(function (f) {
        return '<a href="../' + f.guide + '" data-cta="guide">' +
          (pending ? esc(f.cls) + " guide →" : "User guide →") + "</a>";
      }).join("");
      return '<div class="skf-block' + (changed ? " flash" : "") + '"><span class="skf-role">' +
        esc(b.role) + "</span>" + fc + '<span class="skf-model">' + esc(b.model) + "</span>" +
        '<span class="skf-what">' + esc(b.text) + "</span>" +
        b.tags.map(function (t) { return '<span class="skf-tag">' + esc(t) + "</span>"; }).join("") +
        '<span class="skf-guides">' + guides + "</span></div>";
    }

    function renderAnswer() {
      var P = D.partial[key()];
      var total = rowsShown().length, done = total - P.missing.length;
      var head = '<div class="skf-eyebrow"><span>Your starting point</span><span>' + done +
        " of " + total + " answered</span></div>";
      if (!P.headline) {
        elAnswer.innerHTML = head +
          '<p class="skf-headline pending">Answer the first question to see which forecasters to compare.</p>' +
          '<div class="skf-blocks"><div class="skf-block empty">Forecaster</div>' +
          '<div class="skf-block empty">Forecaster</div></div>';
        previous = {};
        return;
      }
      var now = {}, had = Object.keys(previous).length > 0;
      var blocks = P.blocks.map(function (b) {
        var text = JSON.stringify(b);
        now[b.model] = text;
        return blockHtml(b, previous[b.model] !== undefined ? previous[b.model] !== text : had);
      }).join("");
      previous = now;
      var c = D.combos[key()], B = P.baseline;
      var why = c ? '<div class="skf-why">' + c.why.map(function (w) {
        return "<p>" + esc(w) + "</p>";
      }).join("") + '<p><a href="#how-we-chose-these-rules" data-how>How we chose these rules</a></p></div>' : "";
      var base = '<p class="skf-base">' + esc(B.text) + (B.cls ? " <code>" + esc(B.cls) +
        '</code> · <a href="../' + B.guide + '" data-cta="guide">User guide →</a>' : "") + "</p>";
      elAnswer.innerHTML = head + '<p class="skf-headline">' + esc(P.headline) + "</p>" +
        '<div class="skf-blocks">' + blocks + "</div>" + base + why;
    }

    /* ---------- script ---------- */
    function codeHtml(code) {
      /* One element per line: the first time the script appears its lines come in
         one after another; after a change of answer, only the new lines flash. */
      var lines = code.split("\n"), html = highlight(code).split("\n"), first = lastLines === null;
      return html.map(function (h, n) {
        var cls = first ? "skf-ln reveal"
          : (lastLines[lines[n]] || !lines[n].trim() ? "skf-ln" : "skf-ln changed");
        var delay = first ? ' style="animation-delay:' + Math.min(n * 14, 700) + 'ms"' : "";
        return '<span class="' + cls + '"' + delay + ">" + (h || " ") + "</span>";
      }).join("\n");
    }

    function more(id, title, body) {
      var isOpen = open[id] === true;
      return '<div class="skf-more"><button type="button" data-more="' + id + '" aria-expanded="' +
        isOpen + '">' + esc(title) + '</button><div class="skf-body"' + (isOpen ? "" : " hidden") +
        ">" + body + "</div></div>";
    }

    /* The script as copied for Colab: the install line, the sample data, the rest. */
    function withSample(sample, code) {
      var cut = code.indexOf("\n");
      return code.slice(0, cut) + "\n" + sample + "\n" + code.slice(cut + 1);
    }

    function renderScript() {
      var P = D.partial[key()], c = D.combos[key()];
      var bar = '<div class="skf-bar"><i></i><i></i><i></i><span>first_comparison.py</span>';
      if (!c) {
        /* Outline of the script: what the answers so far already decide */
        var left = P.missing.length;
        var wait = "# Your script appears here when you answer the " +
          (left === 1 ? "last question" : left + " questions left") + ".";
        var outline = P.outline.map(function (s, n) { return "# " + (n + 1) + ". " + s; }).join("\n");
        elScript.innerHTML = '<div class="skf-window">' + bar + '</div><pre class="waiting"><code>' +
          '<span class="tk-m">' + esc(wait + (outline ? "\n#\n# So far it will compare:\n" + outline : "")) +
          "</span></code></pre></div>";
        elScript.data = null;
        lastLines = null;
        return;
      }
      var code = D.snippets[c.snippet], lines = code.split("\n");
      var cut = lines.indexOf("# Example settings so that the script runs: they are not tuned.");
      /* The install line stays visible; the imports are folded */
      var imports = lines.slice(1, cut).join("\n").replace(/\s+$/, "");
      var body = lines.slice(cut).join("\n");
      var shown = lines[0] + "\n" + (showImports ? imports + "\n\n" : "") + body;
      var kind = state.target === "category" ? "category" : "number";
      var history = D.min_history[state.freq];
      var ai = c.skforecast_ai ? more("ai", "Let skforecast-ai compare more models for you",
        "<p>skforecast-ai is a separate package that chooses the settings of each model from your data and tries more of them. Add these lines after the script: they use the same data and the same test periods. Its ranking can differ from the one above.</p>" +
        '<pre class="skf-mini"><code>' + highlight(c.skforecast_ai.replace(/\s+$/, "")) + "</code></pre>" +
        '<div class="skf-actions"><button type="button" class="skf-btn" data-copy="ai">Copy lines</button>' +
        '<a class="skf-btn" href="https://ai.skforecast.org/" target="_blank" rel="noopener" data-cta="skforecast-ai">skforecast-ai docs</a></div>') : "";
      var mcp = c.agent ?
        '<div class="skf-opt2"><p><b>If it supports MCP</b> (Claude Code, Cursor, VS Code, Codex, Claude Desktop): connect the ' +
        '<a href="https://ai.skforecast.org/stable/user-guides/mcp-server.html" target="_blank" rel="noopener" data-cta="mcp">skforecast-ai MCP server</a>' +
        " and ask it in plain language. It runs the comparison with tools and returns the script that ran.</p>" +
        '<div class="skf-say">' + esc(c.agent) + "</div>" +
        '<div><button type="button" class="skf-btn" data-copy="agent">Copy message</button></div></div>' : "";
      elScript.innerHTML =
        "<h3>What the script does</h3>" +
        '<ol class="skf-steps">' + D.script_steps[kind].map(function (s) {
          return "<li>" + esc(s) + "</li>";
        }).join("") + "</ol>" +
        '<div class="skf-window">' + bar + '<button type="button" data-copy="code">Copy</button></div>' +
        '<button type="button" class="skf-fold" aria-expanded="' + showImports + '">' +
        (showImports ? "▾" : "▸") + " imports (" + imports.split("\n").length + " lines)</button>" +
        "<pre><code>" + codeHtml(shown) + "</code></pre></div>" +
        '<p class="skf-caption">Runs as it is: tested on sample data every time it changes. Needs at least ' +
        history[0] + " values" + (history[1] ? " (" + history[1] + ")" : "") + ".</p>" +
        '<div class="skf-actions"><button type="button" class="skf-btn primary" data-copy="code">Copy script</button>' +
        '<a class="skf-btn" href="' + D.colab + '" target="_blank" rel="noopener" data-copy="colab">Run it in Google Colab</a>' +
        '<span class="skf-status" role="status"></span></div>' +
        '<p class="skf-next">Next step: <a href="../' + D.compare_guide + '" data-cta="compare">compare more model families the same way</a>.</p>' +
        ai +
        more("assistant", "Using an AI assistant?", mcp +
          '<div class="skf-opt2"><p><b>' + (c.agent ? "If it does not" : "Any assistant") +
          "</b>: copy the script with instructions to adapt it to your data. The assistant is told to ask for a sample of your data first and to keep the forecasters as they are until the script runs.</p>" +
          '<div><button type="button" class="skf-btn" data-copy="prompt">Copy script as a prompt</button></div></div>') +
        more("notes", "Good to know", "<ul>" + D.notes.map(function (n) {
          return "<li>" + esc(n).replace(/`([^`]+)`/g, "<code>$1</code>") + "</li>";
        }).join("") + "</ul>") +
        '<p class="skf-caption skf-feedback">Was this useful? ' +
        '<button type="button" class="skf-reset" data-feedback="yes">Yes</button> · ' +
        '<button type="button" class="skf-reset" data-feedback="no">No</button></p>';
      lastLines = {};
      shown.split("\n").forEach(function (l) { lastLines[l] = true; });
      elScript.data = {
        code: code,
        colab: withSample(c.sample, code),
        prompt: c.prompt + "```python\n" + code + "```\n",
        ai: c.skforecast_ai || "",
        agent: c.agent || ""
      };
    }

    function copy(text, message) {
      var status = elScript.querySelector(".skf-status");
      function done(ok) {
        if (status) status.textContent = ok ? message : "Could not copy: select the text and copy it";
      }
      try { navigator.clipboard.writeText(text).then(function () { done(true); }, function () { done(false); }); }
      catch (e) { done(false); }
    }

    function update() {
      renderRows(); renderAnswer(); renderScript();
      try {
        history.replaceState(history.state, "", Object.keys(state).length
          ? "#answers=" + key() : location.pathname + location.search);
      } catch (e) { /* preview without history */ }
    }

    /* ---------- interaction ---------- */
    elRows.addEventListener("click", function (e) {
      if (e.target.closest(".skf-reset")) {
        clear(); showImports = false; editing = null; open = {}; update();
        track("finder_reset");
        return;
      }
      var chip = e.target.closest(".skf-chip");
      if (chip) {
        editing = chip.getAttribute("data-edit"); update();
        var first = elRows.querySelector('.skf-opt[tabindex="0"]'); if (first) first.focus();
        return;
      }
      var b = e.target.closest(".skf-opt"); if (!b) return;
      var row = b.getAttribute("data-row"), value = b.getAttribute("data-value");
      state[row] = value;
      if (state.target === "category") delete state.series;
      editing = null;
      update();
      track("finder_change", { row: row, option: value, complete: !!D.combos[key()] });
      var again = elRows.querySelector('.skf-opt[data-row="' + row + '"][data-value="' + value + '"]');
      if (again) again.focus();
    });
    elRows.addEventListener("keydown", function (e) {
      var b = e.target.closest(".skf-opt"); if (!b) return;
      var dir = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key]; if (!dir) return;
      e.preventDefault();
      var opts = Array.prototype.slice.call(b.parentElement.querySelectorAll(".skf-opt"));
      opts[(opts.indexOf(b) + dir + opts.length) % opts.length].click();
    });
    elScript.addEventListener("click", function (e) {
      var t = e.target.closest("[data-copy], [data-more], [data-feedback], .skf-fold, [data-cta]");
      if (!t) return;
      var data = elScript.data, kind = t.getAttribute("data-copy");
      if (kind && data) {
        copy(data[kind], {
          code: "Script copied", prompt: "Prompt copied", ai: "Lines copied", agent: "Message copied",
          colab: "Script copied with sample data: paste it in the second cell of the notebook that just opened."
        }[kind]);
        track("finder_copy", { kind: kind });
      } else if (t.hasAttribute("data-more")) {
        var id = t.getAttribute("data-more");
        open[id] = !open[id];
        t.setAttribute("aria-expanded", open[id]);
        t.nextElementSibling.hidden = !open[id];
        if (open[id]) track("finder_open", { section: id });
      } else if (t.hasAttribute("data-feedback")) {
        track("finder_feedback", { value: t.getAttribute("data-feedback") });
        t.parentElement.textContent = "Thanks for telling us.";
      } else if (t.classList.contains("skf-fold")) {
        showImports = !showImports;
        renderScript();
        var fold = elScript.querySelector(".skf-fold"); if (fold) fold.focus();
      } else {
        track("finder_cta", { target: t.getAttribute("data-cta") });
      }
    });
    elAnswer.addEventListener("click", function (e) {
      var link = e.target.closest("a"); if (!link) return;
      if (link.hasAttribute("data-how")) {
        /* Scroll without changing the hash, which holds the answers */
        var target = document.getElementById("how-we-chose-these-rules");
        if (target) { e.preventDefault(); target.scrollIntoView({ behavior: "smooth" }); }
        track("finder_cta", { target: "how" });
      } else {
        track("finder_cta", { target: link.getAttribute("data-cta") });
      }
    });
    function onHash() { if (fromHash()) update(); }
    function onNarrow() { editing = null; renderRows(); }
    window.addEventListener("hashchange", onHash);
    if (narrow.addEventListener) narrow.addEventListener("change", onNarrow);

    fromHash();
    update();

    return function destroy() {
      window.removeEventListener("hashchange", onHash);
      if (narrow.removeEventListener) narrow.removeEventListener("change", onNarrow);
      document.body.classList.remove("sk-finder-ready");
    };
  }

  function init() {
    var root = document.getElementById("sk-finder");
    if (!root || !root.getAttribute("data-src")) return null;
    var cancelled = false, destroy = null;
    root.setAttribute("data-state", "loading");
    fetch(new URL(root.getAttribute("data-src"), location.href))
      .then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
      .then(function (data) { if (!cancelled) destroy = mount(root, data); })
      .catch(function () {
        /* The static page below stays: rules table and example script */
        if (cancelled) return;
        root.setAttribute("data-state", "error");
        root.textContent = "The interactive finder could not be loaded. The rules and an example script are below.";
      });
    return {
      destroy: function () {
        cancelled = true;
        if (destroy) destroy();
      }
    };
  }

  function onDocument() {
    if (current) current.destroy();
    current = init();
  }
  if (typeof document$ !== "undefined") {
    document$.subscribe(onDocument);
  } else {
    document.addEventListener("DOMContentLoaded", onDocument);
  }
})();
