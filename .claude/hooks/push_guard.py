"""
PreToolUse hook (Bash and GitHub MCP write tools): what reaches GitHub.

Blocks (exit code 2, the reason goes back to Claude):

- Force pushes in any form (`--force`, `--force-with-lease`, `-f` in a cluster
  such as `-uf`, a `+` refspec) and `--all`, `--branches` or `--mirror`, on any
  branch. The deny rules of `.claude/settings.json` only match prefixes.
- Pushes to `main`, which only changes when the release branch is merged into
  it, and deleting `main` or a release branch.
- Branch names generated by Claude Code: cloud sessions (claude.ai/code)
  develop on `claude/<slug>` and `claude --worktree` creates `worktree-<name>`.
  A pull request opened from one keeps that name, so pushing one, opening a
  pull request from one (`gh pr create`) or writing to one with the GitHub MCP
  tools is blocked; creating or renaming it locally is harmless, and deleting
  it is allowed. Other names are not checked: the rule `<type>/<topic>` is in
  CLAUDE.md, and a list of allowed types would block legitimate names.

Asks the user to confirm (an `ask` decision, in any permission mode):

- A push to a release branch (`X.Y.x`) whose commits change package code
  (`skforecast/`, `pyproject.toml`), which normally goes through a pull
  request. Pushing roadmap, docs, harness or AI context changes to it directly
  is the usual workflow and goes through.
- Merging a pull request: `gh pr merge`, `gh api` on `/pulls/N/merge` or the
  `mergePullRequest` mutation, and the GitHub MCP merge tool.

`git push` targets are the destination of each refspec (`HEAD` and `@` are
the current branch) or, with no refspec, the current branch. Heredoc bodies
and redirections are not arguments. Standard library only (Python 3.9+).
"""

import json
import os
import re
import shlex
import subprocess
import sys

SEGMENT_SEPARATOR = re.compile(r"\n|&&|\|\||;|\|")
ENV_ASSIGNMENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
# A redirection (`2>&1`, `>log`, `> log`), which is not an argument; group 1 is
# empty when the target is the next word.
REDIRECTION = re.compile(r"^(?:\d+|&)?(?:>>?|<<?|>&|<&)(.*)$")
# The start of a heredoc (`<<EOF`, `<<'EOF'`, `<<-EOF`), not a here-string (`<<<`).
HEREDOC_START = re.compile(r"(?<!<)<<(?!<)-?\s*['\"]?([A-Za-z_][A-Za-z0-9_]*)['\"]?")
# git options that take a separate value before the subcommand.
GIT_OPTIONS_WITH_VALUE = {"-C", "-c", "--git-dir", "--work-tree", "--namespace"}
# `git push` options that take a separate value.
PUSH_OPTIONS_WITH_VALUE = {"-o", "--push-option", "--repo", "--receive-pack", "--exec"}
FORCE_OPTIONS = ("--force", "--force-with-lease", "--force-if-includes")
ALL_BRANCH_OPTIONS = {"--all", "--branches", "--mirror"}
SESSION_BRANCH = re.compile(r"^(claude/|worktree-)")
RELEASE_BRANCH = re.compile(r"^\d+\.\d+\.x$")
PACKAGE_PATHS = ("skforecast/", "pyproject.toml")
RELEASE_REF = re.compile(
    r"refs/(?:heads|remotes/origin)/(\d+)\.(\d+)\.x$", re.MULTILINE
)
# A pull request merge through `gh api`: REST endpoint or GraphQL mutation.
MERGE_API = re.compile(r"/pulls/\d+/merge\b|mergePullRequest")
TIMEOUT = 15
# GitHub MCP tools that write to a branch and the argument that names it.
MCP_TOOL = re.compile(r"^mcp__.*github.*__(\w+)$")
MCP_BRANCH_ARGUMENT = {
    "create_branch": "branch",
    "push_files": "branch",
    "create_or_update_file": "branch",
    "delete_file": "branch",
    "create_pull_request": "head",
}
MCP_COMMIT_TOOLS = {"push_files", "create_or_update_file", "delete_file"}

FORCE_MESSAGE = (
    "Blocked: force pushes rewrite published history and are not allowed "
    "(CLAUDE.md). Push new commits on top instead; merge the base branch "
    "rather than rebasing a pushed branch. If the pull request of this branch "
    "is already merged, push the follow-up to a new `<type>/<topic>` branch "
    "created from `origin/{release}` instead."
)
ALL_MESSAGE = (
    "Blocked: --all, --branches and --mirror push every local branch, "
    "protected ones included. Push the current branch only."
)
MAIN_MESSAGE = (
    "Blocked: `main` only changes when the release branch is merged into it at "
    "release time. Push a `<type>/<topic>` branch and open the pull request "
    "against `{release}`."
)
DELETE_MESSAGE = "Blocked: deleting '{branch}' is not allowed."
SESSION_MESSAGE = (
    "Blocked: '{branch}' is a branch name generated by Claude Code; branches "
    "that reach GitHub are named `<type>/<topic>` (feature, fix, docs, chore, "
    "perf; see the Git workflow in CLAUDE.md). Rename it with `git branch -m "
    "<type>/<topic>`, check that `git log --oneline origin/{release}..HEAD` "
    "lists only the commits of this work (if the branch started from `main`, "
    "move them with `git rebase --onto origin/{release} origin/main`), and "
    "push that branch instead."
)
MCP_SESSION_MESSAGE = (
    "Blocked: '{branch}' is a branch name generated by Claude Code; branches "
    "that reach GitHub are named `<type>/<topic>` (feature, fix, docs, chore, "
    "perf; see the Git workflow in CLAUDE.md). Use a `<type>/<topic>` name, "
    "created from `origin/{release}`, instead."
)
PACKAGE_MESSAGE = (
    "This pushes package code to the release branch '{branch}' without a pull "
    "request ({files}). Package changes normally go through a `<type>/<topic>` "
    "branch and a pull request (verify, release note link)."
)
NOT_FETCHED_MESSAGE = (
    "This pushes to the release branch '{branch}', but origin/{branch} is not "
    "fetched, so its commits could not be checked for package code (which "
    "normally goes through a pull request)."
)
MERGE_MESSAGE = "Merging a pull request needs the user's confirmation."


class Verdict:
    """The first reason to block, and the reasons to ask."""

    def __init__(self):
        self.block = None
        self.ask = []

    def blocked(self, message):
        self.block = self.block or message


def without_heredocs(command):
    """
    Remove the body of every heredoc from `command`: its lines are data (a
    commit message, a file written with `cat`), not commands, so a line such
    as `git push` in a handoff note must not be checked as if it ran.
    """
    kept = []
    delimiter = None
    for line in command.split("\n"):
        if delimiter is not None:
            if line.strip() == delimiter:
                delimiter = None
            continue
        kept.append(line)
        match = HEREDOC_START.search(line)
        if match:
            delimiter = match.group(1)
    return "\n".join(kept)


def segments(command):
    """
    Split `command` into simple commands and return the words of each, with
    leading env assignments and redirections removed. Heredoc bodies are left
    out, and a segment that is not valid shell is skipped.
    """
    result = []
    for segment in SEGMENT_SEPARATOR.split(without_heredocs(command)):
        try:
            words = shlex.split(segment.strip().lstrip("({ "))
        except ValueError:
            continue
        while words and ENV_ASSIGNMENT.match(words[0]):
            words.pop(0)
        arguments = []
        target = False
        for word in words:
            if target:
                target = False
            elif match := REDIRECTION.match(word):
                target = match.group(1) == ""
            else:
                arguments.append(word)
        if arguments:
            result.append(arguments)
    return result


def git(cwd, *args):
    try:
        result = subprocess.run(
            ["git", *args], cwd=cwd, capture_output=True, text=True,
            timeout=TIMEOUT, env={**os.environ, "GIT_TERMINAL_PROMPT": "0"},
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout if result.returncode == 0 else None


def current_branch(cwd):
    branch = (git(cwd, "rev-parse", "--abbrev-ref", "HEAD") or "").strip()
    return "" if branch == "HEAD" else branch


def release_branch(cwd):
    """
    The release branch in development: the `X.Y.x` branch of `origin` with
    the highest version (from GitHub, or else from the local refs), or None.
    Not `__version__`, which on `main` (where cloud sessions may start) is
    still the previous release.
    """
    refs = []
    for args in (
        ["ls-remote", "--heads", "origin", "refs/heads/*.x"],
        ["for-each-ref", "--format=%(refname)", "refs/remotes/origin/"],
    ):
        refs = [m.groups() for m in RELEASE_REF.finditer(git(cwd, *args) or "")]
        if refs:
            break
    if not refs:
        return None
    major, minor = max((int(a), int(b)) for a, b in refs)
    return f"{major}.{minor}.x"


def ask_for_package_files(verdict, branch, paths):
    """Ask before writing package files directly to a release branch."""
    files = sorted({p for p in paths if p.startswith(PACKAGE_PATHS)})
    if files:
        shown = ", ".join(files[:3]) + (", ..." if len(files) > 3 else "")
        verdict.ask.append(PACKAGE_MESSAGE.format(branch=branch, files=shown))


def pushed_files(cwd, source, branch):
    """
    Files changed by the commits that pushing `source` to `branch` sends, or
    None when `origin/<branch>` is not known locally.
    """
    if git(cwd, "rev-parse", "--verify", "--quiet", f"refs/remotes/origin/{branch}") is None:
        return None
    names = git(cwd, "log", "--name-only", "--format=", f"origin/{branch}..{source}")
    return (names or "").split()


def session_message(branch, mcp=False):
    """
    What to do instead: rename the local branch, or with the GitHub MCP tools
    (which may have no local branch) use another name. `{release}` is filled
    in when blocking.
    """
    message = MCP_SESSION_MESSAGE if mcp else SESSION_MESSAGE
    return message.format(branch=branch, release="{release}")


def check_target(verdict, branch, cwd, source=None, mcp=False):
    """
    Rules for a branch that a push or a GitHub MCP tool writes to. `source` is
    the ref pushed, whose commits are compared with `origin/<branch>`.
    """
    if SESSION_BRANCH.match(branch):
        verdict.blocked(session_message(branch, mcp))
    elif branch == "main":
        verdict.blocked(MAIN_MESSAGE)
    elif RELEASE_BRANCH.match(branch) and source is not None:
        files = pushed_files(cwd, source, branch)
        if files is None:
            verdict.ask.append(NOT_FETCHED_MESSAGE.format(branch=branch))
        else:
            ask_for_package_files(verdict, branch, files)


def check_push(verdict, args, cwd):
    """Rules for `git push <args>` run in `cwd`."""
    positional = []
    i = 0
    while i < len(args):
        if args[i] in PUSH_OPTIONS_WITH_VALUE:
            i += 2
            continue
        if not args[i].startswith("-"):
            positional.append(args[i])
        i += 1
    # With `--repo` the remote is an option, so every positional is a refspec.
    has_repo = any(a == "--repo" or a.startswith("--repo=") for a in args)
    refspecs = positional if has_repo else positional[1:]
    branch = current_branch(cwd)

    if "--delete" in args or "-d" in args:
        for name in refspecs:
            name = name.removeprefix("refs/heads/")
            if name == "main" or RELEASE_BRANCH.match(name):
                verdict.blocked(DELETE_MESSAGE.format(branch=name))
        return
    for arg in args:
        if arg.startswith(FORCE_OPTIONS) or (
            arg.startswith("-") and not arg.startswith("--") and "f" in arg[1:]
        ):
            verdict.blocked(FORCE_MESSAGE)
    if any(refspec.startswith("+") for refspec in refspecs):
        verdict.blocked(FORCE_MESSAGE)
    if ALL_BRANCH_OPTIONS.intersection(args):
        verdict.blocked(ALL_MESSAGE)

    for refspec in refspecs or [branch]:
        src, colon, dst = refspec.lstrip("+").partition(":")
        if colon and not src:
            name = dst.removeprefix("refs/heads/")
            if name == "main" or RELEASE_BRANCH.match(name):
                verdict.blocked(DELETE_MESSAGE.format(branch=name))
            continue  # `:branch` deletes it.
        target = (dst or src).removeprefix("refs/heads/")
        if target in ("HEAD", "@"):
            target = branch
        if target:
            source = "HEAD" if src in ("", "HEAD", "@") else src
            check_target(verdict, target, cwd, source)


def pr_head(args, cwd):
    """Head branch of `gh pr create <args>` (the current one by default)."""
    for i, arg in enumerate(args):
        if arg in ("--head", "-H") and i + 1 < len(args):
            head = args[i + 1]
        elif arg.startswith("--head="):
            head = arg.split("=", 1)[1]
        else:
            continue
        return head.split(":", 1)[-1]
    return current_branch(cwd)


def check_bash(verdict, command, cwd):
    for words in segments(command):
        name = os.path.basename(words[0])
        if name == "git":
            repo = cwd
            i = 1
            while i < len(words) and words[i].startswith("-"):
                if words[i] == "-C" and i + 1 < len(words):
                    repo = os.path.join(repo, words[i + 1])
                i += 2 if words[i] in GIT_OPTIONS_WITH_VALUE else 1
            if words[i:i + 1] == ["push"]:
                check_push(verdict, words[i + 1:], repo)
        elif name == "gh" and words[1:3] == ["pr", "create"]:
            head = pr_head(words[3:], cwd)
            if SESSION_BRANCH.match(head):
                verdict.blocked(session_message(head))
        elif name == "gh" and (
            words[1:3] == ["pr", "merge"]
            or (words[1:2] == ["api"] and any(MERGE_API.search(w) for w in words[2:]))
        ):
            verdict.ask.append(MERGE_MESSAGE)


def check_mcp(verdict, tool, tool_input, cwd):
    if tool == "merge_pull_request":
        verdict.ask.append(MERGE_MESSAGE)
        return
    branch = str(tool_input.get(MCP_BRANCH_ARGUMENT.get(tool, ""), "") or "")
    branch = branch.split(":", 1)[-1]
    if not branch:
        return
    if tool not in MCP_COMMIT_TOOLS:
        if SESSION_BRANCH.match(branch):
            verdict.blocked(session_message(branch, mcp=True))
        return
    check_target(verdict, branch, cwd, mcp=True)
    if RELEASE_BRANCH.match(branch):
        paths = [tool_input.get("path")] + [
            f.get("path") for f in tool_input.get("files") or [] if isinstance(f, dict)
        ]
        ask_for_package_files(verdict, branch, [p for p in paths if isinstance(p, str)])


def main():
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        return 0

    tool_name = payload.get("tool_name", "")
    tool_input = payload.get("tool_input") or {}
    cwd = payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or "."

    verdict = Verdict()
    if tool_name == "Bash":
        check_bash(verdict, tool_input.get("command", ""), cwd)
    elif match := MCP_TOOL.match(tool_name):
        check_mcp(verdict, match.group(1), tool_input, cwd)

    if verdict.block:
        project_dir = os.environ.get("CLAUDE_PROJECT_DIR") or cwd
        release = release_branch(project_dir) or "X.Y.x"
        sys.stderr.write(verdict.block.format(release=release) + "\n")
        return 2
    if verdict.ask:
        print(json.dumps({
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "ask",
                "permissionDecisionReason": " ".join(dict.fromkeys(verdict.ask)),
            }
        }))
    return 0


if __name__ == "__main__":
    sys.exit(main())
