"""
PostToolUse hook (GitHub MCP `create_pull_request`): attribution footer added
by the server.

In a cloud session the GitHub MCP server appends a "Generated by
[Claude Code](session link)" footer to the body after the call has passed
`attribution_guard.py`, so no PreToolUse hook can see it. The tool only
returns the id and URL of the pull request, so this hook cannot tell whether
the footer is there; it asks Claude to read the pull request back and remove
it.

Adapted from `.claude/hooks/post_pr_footer.py` in skforecast/skforecast-ai.
Exit code 2 sends the request on stderr back to Claude (the pull request
already exists). Standard library only (runs on any Python 3).
"""

import json
import re
import sys

PULL_URL = re.compile(r"/pull/(\d+)")


def main():
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        payload = {}

    response = json.dumps(payload.get("tool_response", ""))
    match = PULL_URL.search(response)
    target = f"pull request #{match.group(1)}" if match else "the pull request"
    sys.stderr.write(
        f"The GitHub MCP server may have appended a 'Generated by Claude Code' "
        f"footer with the session link to the body of {target} after the "
        f"call. Pull requests are authored by the user alone (AGENTS.md): "
        f"read it back with the pull request read tool and, if the body ends "
        f"with that footer (a '---' line and '_Generated by [Claude Code]"
        f"(...)_'), call the update pull request tool with the same body "
        f"without it. Read it once more: if the footer is still there, do not "
        f"retry; tell the user to remove it by hand on GitHub.\n"
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())
